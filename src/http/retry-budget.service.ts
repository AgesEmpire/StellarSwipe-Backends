import { Injectable, Logger } from '@nestjs/common';

/**
 * #1376 — Shared retry budgets to prevent retry storms.
 *
 * `HttpRetryService` already bounds *how many times a single call* may be
 * retried (`maxAttempts`), but that is a per-call limit: if an outbound
 * dependency degrades, every in-flight caller can independently exhaust its
 * own attempt budget at the same time, multiplying load on an already
 * struggling provider ("retry storm").
 *
 * `RetryBudgetService` adds a second, shared layer on top of that: a token
 * bucket per budget key (typically the provider name, or "default" when no
 * provider is set) that caps the *rate* of retries allowed across *all*
 * callers sharing that key. Once the bucket is empty, further retries for
 * that key fail fast — the caller gets its last real error immediately
 * instead of adding another delayed attempt — until tokens refill.
 *
 * This is deliberately simple (in-memory, per-instance) rather than a
 * distributed budget: it bounds load generated by *this* process, which is
 * what actually hits the network, and avoids adding a hard dependency on
 * shared state for a safety mechanism that must keep working even when
 * shared infrastructure (e.g. Redis) is itself degraded.
 */
export interface RetryBudgetOptions {
  /** Maximum burst of retries allowed before the bucket must refill. Default: 10. */
  capacity?: number;
  /** Sustained retries/second allowed once the burst is exhausted. Default: 2. */
  refillPerSecond?: number;
}

interface Bucket {
  tokens: number;
  lastRefillAt: number;
}

const DEFAULT_OPTIONS: Required<RetryBudgetOptions> = {
  capacity: 10,
  refillPerSecond: 2,
};

@Injectable()
export class RetryBudgetService {
  private readonly logger = new Logger(RetryBudgetService.name);
  private readonly buckets = new Map<string, Bucket>();

  /**
   * Attempts to consume one retry token for `key`. Returns `true` when a
   * retry is within budget, `false` when the budget is exhausted and the
   * retry should be skipped (fail fast).
   */
  tryConsume(key: string, options?: RetryBudgetOptions): boolean {
    const opts = { ...DEFAULT_OPTIONS, ...options };
    const bucket = this.refill(key, opts);

    if (bucket.tokens < 1) {
      this.logger.warn(
        `[RetryBudget] "${key}" retry budget exhausted — failing fast instead of retrying`,
      );
      return false;
    }

    bucket.tokens -= 1;
    return true;
  }

  /** Current token count for a key, mostly for diagnostics/tests. */
  getTokens(key: string, options?: RetryBudgetOptions): number {
    const opts = { ...DEFAULT_OPTIONS, ...options };
    return this.refill(key, opts).tokens;
  }

  /** Resets a key's bucket back to full capacity (admin/test use). */
  reset(key: string): void {
    this.buckets.delete(key);
  }

  private refill(key: string, opts: Required<RetryBudgetOptions>): Bucket {
    const now = Date.now();
    let bucket = this.buckets.get(key);

    if (!bucket) {
      bucket = { tokens: opts.capacity, lastRefillAt: now };
      this.buckets.set(key, bucket);
      return bucket;
    }

    const elapsedSeconds = Math.max(0, now - bucket.lastRefillAt) / 1000;
    const refillAmount = elapsedSeconds * opts.refillPerSecond;
    if (refillAmount > 0) {
      bucket.tokens = Math.min(opts.capacity, bucket.tokens + refillAmount);
      bucket.lastRefillAt = now;
    }

    return bucket;
  }
}
